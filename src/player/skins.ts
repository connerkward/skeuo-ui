// bump when frames/sprites are regenerated so browsers re-fetch
const ASSET_VERSION = "nb21";
const base = (id: string) => `/skins/${id}`;
export const layerUrl = (id: string, layer: Layer) => `${base(id)}/${layer}.png?v=${ASSET_VERSION}`;
// Built-in skins draw control sprites from their donor STYLE's bundled set
// (public/skins/<style>/sprites/). Runtime/generated skins draw from their OWN
// per-skin sprites served by the API (/api/asset/skins/<id>/sprites/<name>.png);
// pass runtime=true to resolve there. The asset-version cache-bust is bundled-
// only — the API path is per-skin and already unique, so it's skipped there.
export const spriteUrl = (id: string, name: string, runtime?: boolean) =>
  runtime
    ? `/api/asset/skins/${id}/sprites/${name}.png`
    : `${base(skinStyle(id))}/sprites/${name}.png?v=${ASSET_VERSION}`;
// a ~256px WebP of the frame (~5–15 KB) for the mobile filmstrip minis — the full
// frame.png is 2–5 MB, far too heavy to load dozens of for tiny thumbnails.
// Generated by scripts/gen-thumbs.sh into public/skins/<id>/thumb.webp.
export const thumbUrl = (id: string) => `${base(id)}/thumb.webp?v=${ASSET_VERSION}`;

export function skinHas(id: string, layer: Layer): boolean {
  const s = skinList.find((x) => x.id === id);
  return !!s?.has.includes(layer);
}
