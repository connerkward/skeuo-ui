import type { Layer } from "../template/schema";

// Per-skin asset registry. Layered architecture:
//   frame              = AI faceplate (bezel + blank panel, no controls/screens)
//   sprites/           = AI control sprites WITH STATES (switch-off/on, knob,
//                        button, thumb) — composited live by React
//   screens + content  = CSS recessed screens with live React content
// CSS approximations are the fallback when a layer is missing.
export interface SkinAssets {
  id: string;
  name: string;
  blurb: string;
  has: Layer[];
  // the generated frame image bakes in the controls + screens, so React
  // renders only transparent interactive overlays + live screen content
  baked?: boolean;
  // skins whose layout was EXTRACTED from a freeform design carry their own
  // template (fetched at runtime) instead of the canonical one
  templateUrl?: string;
  // CSS palette to use (the [data-skin] value); defaults to id.
  style?: string;
  // wild-shaped skins with CV-detected screen regions
  live?: boolean;
  // AI control sprites with states exist under /skins/<id>/sprites/
  sprites?: boolean;
  // sprite/palette donor only — not shown in the skin list
  hidden?: boolean;
  // sprites/btn-{prev,play,pause,stop,next}.png exist — molded transport faces
  molded?: boolean;
}

export function skinLive(id: string): boolean {
  return !!skinList.find((x) => x.id === id)?.live;
}

// Human-facing display name (without the ✦ marker) and one-line blurb, used by
// the IG export layout. Falls back to the raw id when the skin isn't registered
// (e.g. a runtime-generated skin).
export function skinName(id: string): string {
  const n = skinList.find((x) => x.id === id)?.name;
  return (n ? n.replace(/\s*✦\s*$/, "") : id).trim();
}
export function skinBlurb(id: string): string {
  return skinList.find((x) => x.id === id)?.blurb ?? "";
}

export function skinStyle(id: string): string {
  const s = skinList.find((x) => x.id === id);
  return s?.style ?? id;
}

// sprites resolve through `style`, so a wild body (own frame/template) mounts
// its base style's control sprites.
//
// Runtime/generated skins are NOT in this registry; instead they carry their OWN
// per-skin sprites under /api/asset/skins/<id>/sprites/<bind>.png. When `runtime`
// is true (a RuntimeSkin with sprites), these report sprites-present and resolve
// to that per-skin path. When false (built-in skins), behaviour is unchanged.
export function skinSprites(id: string, runtime?: boolean): boolean {
  if (runtime) return true;
  const sid = skinStyle(id);
  return !!skinList.find((x) => x.id === sid)?.sprites;
}

// Generated skins ship their own molded transport faces (btn-prev/play/…png)
// alongside the rest of their per-skin sprites, so runtime skins are molded too.
export function skinMolded(id: string, runtime?: boolean): boolean {
  if (runtime) return true;
  const sid = skinStyle(id);
  return !!skinList.find((x) => x.id === sid)?.molded;
}

